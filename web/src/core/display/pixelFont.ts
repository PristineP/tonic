  /** Each glyph is seven rows; bit 4 is the leftmost pixel. */
  export const glyphs: Map<string, number[]> = new Map()

  function def(c: string, rows: string[]): void {
    if (rows.length !== 7) throw new Error(`glyph ${c} must have 7 rows`)
    glyphs.set(
      c,
      rows.map((row) => {
        if (row.length !== 5) throw new Error(`glyph ${c} rows must be 5 wide`)
        let v = 0
        for (const ch of row) v = (v << 1) | (ch === '#' ? 1 : 0)
        return v
      }),
    )
  }

